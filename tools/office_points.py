# -*- coding: utf-8 -*-
"""Station slot paths of the V7.9 r4 office / plant points the 3D page reads, and the r4 alarms (3D alarm list).
Built from the same layer code as the station (layer_sim / check_v79_refs stub), so the page and the station cannot drift apart.
usage: python3 office_points.py [graphics3d/data/office_points.json]      --check: exit 1 if the committed file is stale (CI)"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_v6 as M6
import layer_sim
import v79_office as OF

OUT = os.path.join(HERE, '..', 'graphics3d', 'data', 'office_points.json')
AHU_PTS = ('Status', 'StartCmd', 'SAT', 'SAT_SP', 'DuctSP', 'DuctSP_SP', 'FanSpeedCmd', 'ValveCmd', 'OAFlow', 'OAFlowSP', 'OADamperCmd',
           'RADamperCmd', 'RelDamperCmd', 'RAT', 'MAT', 'RA_RH', 'RA_CO2', 'FilterDP', 'PressureRequests', 'CoolingRequests',
           'SpeedFb', 'OADmpFb', 'RADmpFb', 'RelDmpFb', 'PICVFb')                       # r5: field feedbacks (R9 devices on the 3D page)
VAV_PTS = ('Airflow', 'AirflowSP', 'DmpCmd', 'DmpFb', 'CoolSPActive', 'OOS', 'Vmax')
EFFECT = [(r'SensorFault|MeterFault', 'sensor'), (r'DamperFault|Mismatch', 'valve'), (r'HighStatic', 'pressure'), (r'Freeze', 'freeze'),
          (r'BasinLowLow', 'lowlevel'), (r'Flood', 'overflow'), (r'LowDeltaT|Reconcile|NotTracking|VentilationLow|LowAirflow|VeryLowAirflow', 'perf')]


def equip_of(n):
    m = re.match(r'(VAV|RM|TE)_(.+?)_[A-Za-z0-9]+Alarm$', n)
    if m: return [f"RM:{m.group(2).replace('_', '-')}"]                 # room (VAV + sensor) in the office layer
    m = re.match(r'AHU_F(\d\d)_', n)
    if m: return [f'AHU-F{m.group(1)}']
    m = re.match(r'(CH|CHP|CDP)(\d\d)_', n)
    if m: return [f'{m.group(1)}-{m.group(2)}']
    m = re.match(r'CT(\d\d)_', n)
    if m: return [f'CT-{m.group(1)}/1', f'CT-{m.group(1)}/2']
    m = re.match(r'(BTU|PM)_F(\d\d)_', n)
    if m: return [f'FLOOR-{m.group(2)}']
    m = re.match(r'Zone_F(\d\d)_', n)
    if m: return [f'FLOOR-{m.group(1)}']
    return ['CP-01']


def build():
    M6.COS.clear()
    S = layer_sim.build('fpt')
    od = OF.od(); pts = {}
    for r in od['rooms']:
        for x in ('T', 'RH', 'CO2', 'Occ'): pts[f"RM_{OF.nm(r['id'])}_{x}"] = None
    for t in od['airTerminals']:
        v = f"VAV_{OF.nm(t['room'])}"
        for x in VAV_PTS: pts[f'{v}_{x}'] = None
        pts[f'Gfx_{v}_Fwd'] = None
    for fl in range(2, 9):
        for x in AHU_PTS: pts[f'AHU_F{fl:02d}_{x}'] = None
    for m in od['floorMeters']:
        p = f"F{m['floor']:02d}"
        for x in (f'BTU_{p}_kW', f'BTU_{p}_DeltaT', f'FM_{p}_Flow', f'TT_S_{p}', f'TT_R_{p}', f'PM_{p}_kW'): pts[x] = None
    for t in od['tenantMetering']: pts[f"PM_{OF.nm(t['tenantId'])}_kW"] = None
    for d in od['motorizedDampers']:                                     # r5: toilet / janitor exhaust dampers
        if not d.get('integralVAV'):
            for x in ('DmpCmd', 'DmpFb'): pts[f"TE_{OF.nm(d['room'])}_{x}"] = None
    missing = [n for n in pts if n not in S.comp]
    if missing: raise SystemExit('points not built by the layer: ' + ', '.join(missing[:10]))
    points = {n: S.path_of(n) for n in pts}
    alarms = []
    for n, (av, cls, text) in sorted(M6.COS.items()):
        if n not in S.comp or n in S.base: continue
        x = next((e for pat, e in EFFECT if re.search(pat, n)), 'airside')
        alarms.append({'n': n, 's': S.path_of(n), 'c': cls, 't': text, 'e': equip_of(n), 'x': x, 'av': av})
    return {'note': 'generated by tools/office_points.py - do not edit', 'points': points, 'alarms': alarms}


if __name__ == '__main__':
    path = next((a for a in sys.argv[1:] if not a.startswith('--')), OUT)
    data = json.dumps(build(), ensure_ascii=False, indent=0, sort_keys=True)
    if '--check' in sys.argv:
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
        if cur != data:
            print('office_points.json is stale: run tools/office_points.py'); sys.exit(1)
        print('office_points.json up to date'); sys.exit(0)
    open(path, 'w', encoding='utf-8').write(data)
    d = json.loads(data); print('wrote', path, len(d['points']), 'points', len(d['alarms']), 'alarms')
